// Bundles every file in /data into a TypeScript module so the corpus ships
// with the serverless functions on Vercel (no runtime file-system reads).
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(root, "data");
const outFile = join(root, "src", "lib", "data", "corpus.generated.ts");

const files = readdirSync(dataDir)
  .filter((f) => /\.(md|txt)$/i.test(f))
  .sort()
  .map((name) => ({ name, content: readFileSync(join(dataDir, name), "utf8") }));

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/build-corpus.mjs. Do not edit.\n` +
    `export const CORPUS: { name: string; content: string }[] = ${JSON.stringify(files)};\n`,
);
console.log(`corpus: bundled ${files.length} files`);
